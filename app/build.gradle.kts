// 本机 proot/ARM64 环境需要 linux-aarch64 的 aapt2；
// GitHub Actions 的 x86_64 runner 必须用官方默认产物，所以用系统属性开关隔离。
// 本地构建：./gradlew assembleDebug -PforceArm64Aapt2=true
// CI 构建：不传该属性，走默认 linux-x86_64
if (providers.gradleProperty("forceArm64Aapt2").getOrNull() == "true") {
    configurations.all {
        resolutionStrategy.eachDependency {
            if (requested.group == "com.android.tools.build" && requested.name == "aapt2") {
                useTarget("com.android.tools.build:aapt2:${'$'}{requested.version}:linux-aarch64")
            }
        }
    }
}

